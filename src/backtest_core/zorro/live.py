"""Bring what a live sleeve starts from up to date with the bar store.

    python -m backtest_core.zorro.live            (from a desktop session: it runs Zorro)

Run it after every update of the bar store, and always after a roll: the history and the state files are on the
adjusted price scale, which equals the traded contract's prices only since the last roll.

1. ``.t6`` history of every futures root, all years (a roll rescales every earlier bar), and the raw-price NQ history
   of the noise-area sleeve (``NQF``).
2. ``Strategy/ZZFactors.h``, the roll table the scripts read.
3. The state files a ``-d LIVE`` start loads, exported to the end of the history: the dip-buy closes and the
   break touch speeds.

4. The ``Symbol`` of the futures rows in ``History/AssetsLive.csv`` and ``AssetsIBPaper.csv``: the contract each root
   trades next (``traded_id``, Hermes spec 004), so the history and the traded contract cannot disagree. A root is held
   back while any sleeve's state file shows an open trade in it, and a series with no contract table leaves the rows
   as they are.
"""
from __future__ import annotations

import json
import os
from datetime import date, datetime, time, timedelta, timezone
from pathlib import Path

import polars as pl

from .. import bars
from . import assets, export, paths, run

ROOTS = ("CL", "GC", "ES", "NQ")                       # the order of the blocks in ZZFactors.h
STATE_SCRIPTS = ("DipBuyNQ", "BreakGC", "BreakES")
DAILY_STATE = {"DipBuyNQ": "NQ"}                       # state files with one row per session
HEADER = """// ZZFactors.h -- generated by backtest_core.zorro.live; do not edit.
// Roll table per market: factor (adjusted / raw price) FV[j] applies from the bar closing at FT[j]
// (whole minutes since 1899-12-30, UTC) until the next entry. Minutes, not DATE values: a decimal
// DATE literal lost minutes of precision in lite-C and moved a GC roll.
"""


def write_factors(dest: Path | None = None) -> None:
    """``ZZFactors.h`` into ``dest`` (default: the repo's script folder, which ``run.deploy`` copies into Zorro).
    The paper replay writes it straight into its own Zorro copy, so the repo file does not change every day."""
    text = HEADER + "\n" + "\n".join(export.factor_block(r) for r in ROOTS)
    ((dest or paths.SCRIPTS_DIR) / "ZZFactors.h").write_text(text, encoding="ascii", newline="\r\n")


def drop_open_session(script: str, root: str) -> None:
    """Remove the last close from a daily state file when the history stops inside that session.

    The export writes one close per bar, and the last bar is cut short when the bar store ends mid-session. A
    live start skips every session the file holds, so a half session there would hide the real close for good.
    """
    last = bars.intraday(root, "databento", "1m", ["start"])["start"].max()
    if time(16, 55) <= last.time() < time(18, 0):       # the session's last minutes are in: it is complete
        return
    open_session = (last + timedelta(hours=6)).strftime("%Y%m%d")
    f = paths.ZORRO_DIR / "Data" / f"{script}_state.csv"
    lines = f.read_text().splitlines()
    kept = [x for x in lines if not x.startswith(open_session + ",")]
    f.write_text("\n".join(kept) + "\n")
    print(f"{script}: dropped {len(lines) - len(kept)} close of the open session {open_session}", flush=True)


ASSET_LISTS = ("AssetsLive.csv", "AssetsIBPaper.csv")


def open_roots(log_dir: Path | None = None) -> dict[str, str]:
    """``{root: script}`` for every root in which a sleeve's state file (``Log/State_<Script>.csv``) shows an open,
    filled trade of its own (layers 0 and 1; pending entries do not count)."""
    out = {}
    for f in sorted((log_dir or paths.log_dir()).glob("State_*.csv")):
        for line in f.read_text(encoding="utf-8", errors="replace").splitlines()[1:]:
            c = line.split(",")
            if len(c) < 7 or line.startswith("#"):
                continue
            asset, layer, pending, lots = c[2], c[3], c[4], c[6]
            if asset in assets.LIVE_ROWS and layer != "2" and pending == "0" and lots not in ("0", ""):
                out[assets.LIVE_ROWS[asset][0]] = f.stem.removeprefix("State_")
    return out


def traded_id(store, root: str, source: str) -> int:
    """The contract the next session trades: the last bar's, or the incoming one of a roll at the close after it (on
    a roll weekend the newest bar is still the old contract's)."""
    last = bars.intraday(root, source, "1m", ["start", "instrument_id"]).tail(1)
    at = last.select(pl.col("start").dt.replace_time_zone("America/New_York").dt.convert_time_zone("UTC"))["start"][0]
    try:
        after = store.read_rolls(root, source).filter(pl.col("roll_at") > at)
    except LookupError:
        after = None
    return int(after["new_id"][-1]) if after is not None and after.height else int(last["instrument_id"][0])


def _asset_list_rows(path: Path, contract: dict[str, dict], held: dict[str, str]) -> dict:
    """Move one asset list's futures rows to ``contract[root]``, except roots in ``held``. Returns ``{name: change}``."""
    current = assets.read_symbols(path)
    want, notes = {}, {}
    for asset in (a for a in current if a in assets.LIVE_ROWS):
        root = assets.LIVE_ROWS[asset][0]
        new = assets.live_symbol(asset, contract[root])
        if new == current[asset]:
            notes[asset] = "unchanged"
        elif root in held:
            notes[asset] = f"held back by {held[root]}"
        else:
            want[asset] = new
    rows = {**notes, **(assets.write_symbols(path, want) if want else {})}
    for asset, what in rows.items():
        print(f"  {path.name} {asset}: {what}", flush=True)
    return rows


def write_asset_rows(source: str = "databento", history: Path | None = None,
                     log_dir: Path | None = None) -> dict[str, dict]:
    """Point each futures row at the contract its root trades next (``traded_id``). Returns ``{list: {name: change}}`` where
    a change is ``(old, new)``, ``"held back by <Script>"`` or ``"unchanged"``, and writes it with the held-back roots
    to ``Log/AssetRows.json`` for the week start (argus ``prep``), which starts no sleeve on a held-back root."""
    from store_core import BarStore
    store = BarStore(os.environ["BARS_DIR"])
    held = open_roots(log_dir)
    last_contract = {}
    for root in ROOTS:
        try:
            table = store.read_contracts(root, source)
        except LookupError:
            print(f"asset rows left as they are: the {source} series of {root} has no contract table", flush=True)
            return {}
        last_contract[root] = table.filter(pl.col("instrument_id") == traded_id(store, root, source)).row(0, named=True)
    report = {name: _asset_list_rows((history or paths.history_dir()) / name, last_contract, held) for name in ASSET_LISTS}
    _write_report(report, source, log_dir or paths.log_dir())
    return report


def _write_report(report: dict[str, dict], source: str, log_dir: Path) -> None:
    held_back = sorted({assets.LIVE_ROWS[a][0] for r in report.values() for a, w in r.items() if str(w).startswith("held")})
    rows = {k: {a: list(w) if isinstance(w, tuple) else w for a, w in v.items()} for k, v in report.items()}
    log_dir.joinpath("AssetRows.json").write_text(
        json.dumps({"written": datetime.now(timezone.utc).isoformat(timespec="seconds"), "source": source,
                    "held_back": held_back, "rows": rows}, indent=2), encoding="utf-8")


def refresh(factors_in_zorro: bool = False, low_priority: bool = False) -> None:
    """``factors_in_zorro``: write ``ZZFactors.h`` into the Zorro folder after the deploy (the paper replay's copy),
    not into the repo before it."""
    for r in ROOTS:
        n = export.t6(r)
        last = bars.intraday(r, "databento", "1m", ["start"])["start"].max()
        print(f"{r}: {sum(n.values()):,} bars in {len(n)} year files, history ends {last} ET", flush=True)
    n = export.write_noise_area_nq()
    print(f"NQF: {sum(n.values()):,} bars in {len(n)} year files (raw prices, NoiseAreaNQ)", flush=True)
    if factors_in_zorro:
        run.deploy()
        write_factors(paths.strategy_dir())
    else:
        write_factors()
        run.deploy()
    today = int(date.today().strftime("%Y%m%d"))
    for s in STATE_SCRIPTS:
        run.run(s, 0, today, defines=["STATE_LATEST"], timeout=3600, low_priority=low_priority)
        print(f"{s}: state exported", flush=True)
    for script, root in DAILY_STATE.items():
        drop_open_session(script, root)
    write_asset_rows()
    for f in sorted((paths.ZORRO_DIR / "Data").glob("*_state.csv")) + sorted((paths.ZORRO_DIR / "Data").glob("*_touches.csv")):
        lines = f.read_text().splitlines()
        print(f"  {f.name}: {len(lines):,} rows, last {lines[-1]}", flush=True)


if __name__ == "__main__":
    refresh()
